// vulkan/src/kernels/elementwise.cpp - the first engine kernel entry point this port IMPLEMENTS rather than stubs.
//
// strata::kernels::add_inplace is `dst[i] += src[i]` (include/strata/kernels/elementwise.hpp:52).  Until this file it
// was answered by a generated stub in vulkan/src/engine/stubs.cpp, whose body prints the name and exits 3
// (vulkan/src/engine/missing.cpp); that stub is gone, and vulkan/tools/gen_stubs.py now lists this entry point as one
// with a real body so a regeneration does not put it back.
//
// What it is a copy of, entry for entry, is the CUDA body it replaces (src/kernels/cuda/elementwise.cu):
//   :57   __global__ void add_kernel(float* __restrict__ dst, const float* __restrict__ src, long long n)
//             { const long long i = (long long) blockIdx.x * blockDim.x + threadIdx.x; if (i < n) dst[i] += src[i]; }
//   :83   grid_for(n) = (n + THREADS - 1) / THREADS, THREADS = 256
//   :159  `if (n <= 0) return;`                - a zero-length launch is illegal and n == 0 is a real call
//   :160  add_kernel<<<grid_for(n), THREADS, 0, (cudaStream_t) stream>>>(dst, src, n)
//   :161  check_launch("add_inplace")           - the launch's own error, reported, not swallowed
//   :162  sync_if_needed(stream, "add_inplace") - with no stream, CUDA synchronises the device before returning
// The i < n guard lives in the SPIR-V (vulkan/shaders/elementwise_add.comp), because that is where the invocation index
// is; everything above the launch is host code and is here.
//
// THE ARGUMENT BLOB, and where each of its four words ends up.  A SPIR-V entry point takes one parameter block, so the
// CUDA call's four arguments are packed in CUDA's order into four uint64 words:
//   word 0  dst      -> push constant at byte 0 AND storage binding 0
//   word 1  src      -> push constant at byte 8 AND storage binding 1
//   word 2  n        -> push constant at byte 16 (the only member the shader reads: `if (long(i) < pc.n)`)
//   word 3  stream   -> push constant at byte 24 (not read by the shader; the stream is what cfg.stream selects)
// 32 bytes total, which is under this card's maxPushConstantsSize (256 B), so strata::gpu::register_pipeline takes the
// push-constant route (Pipeline::push_params true, param_binding 0), and record_dispatch then binds the first
// `storage_bindings` = 2 words at binding p.param_binding + (p.push_params ? 0 : 1) + i = 0 and 1 - the same two
// bindings the shader declares as `buffer Dst` (binding 0) and `buffer Src` (binding 1).  Each binding is the address's
// own span: offset inside its block, which the sub-allocator may have put past 4 GiB, range clamped to the card's
// 4095 MiB block limit (bind_span).  The two routes are not alternatives here: the blob is pushed AND bound.
//
// WHY THE PIPELINE IS REGISTERED LAZILY, ONCE.  register_pipeline builds a VkShaderModule / VkDescriptorSetLayout /
// VkPipelineLayout / VkPipeline on every device this process opened, and an entry point that is never called should not
// cost that.  The first call to add_inplace pays it; a function-local static makes it exactly once, and a failure is
// remembered instead of retried per call - reported on stderr at the point it happened (see the comment on the static).
